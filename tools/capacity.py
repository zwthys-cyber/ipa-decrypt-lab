MAX_ARTIFACT_BYTES = MAX_IPA_BYTES + ARCHIVE_OVERHEAD
MAX_EXPANDED_BYTES = 3 * MAX_IPA_BYTES
MIN_FREE_BYTES = 3 * MAX_IPA_BYTES + 2 * 1024**3
DOWNLOAD_TIMEOUT = 1200
DECRYPT_TIMEOUT = 900
CRYPTO_TIMEOUT = 600
TELEGRAM_TIMEOUT = 1200
